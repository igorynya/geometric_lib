
def area(a):
    '''
    Возвращает площадь квадрата.

        Параметр:
            a (int/double): сторона квадрата

        Возвращаемое значение:
            area_square (int/double): площадь квадрата
    '''
    return a * a


def perimeter(a):
    '''Принимает число a (сторона квадрата) и возвращает площадь квадрата'''
    return 4 * a
